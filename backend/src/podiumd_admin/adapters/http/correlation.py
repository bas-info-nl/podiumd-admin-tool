"""The correlation id of a request, recorded in Audit Entries and shown on error pages.

Spec: audit-log, "What is recorded" (a correlation id for the request) and
ui-shell, "Error and status pages". The id is generated by the server for
every request; a value sent by the client is never adopted, so it cannot
inject text into the Audit Log.
"""

from __future__ import annotations

import uuid

from fastapi import Request


def correlation_id(request: Request) -> str:
    """The id of this request; the same value for every dependency of one request."""
    existing = getattr(request.state, "correlation_id", None)
    if isinstance(existing, str):
        return existing
    value = uuid.uuid4().hex
    request.state.correlation_id = value
    return value
